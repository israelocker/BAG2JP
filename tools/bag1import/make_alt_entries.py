#!/usr/bin/env python3
"""Turn disc-overlay test mods (BAG1 versions of BAG2 archive entries) into alternate copies stored in
DUMMY.BIN, so both versions coexist and the bag1-content plugin picks one per player at runtime.

BAG2 reads every BUST2.BIN entry through FUN_8001F874(entry, dest), which takes the entry's offset and
size from the RAM copy of the DF2_ table at 0x8005D418 (+8 + 8*entry). DUMMY.BIN (LBA 224035, 13500
Mode-2 Form-1 sectors of zeros) is never read by the game, so the alternate entries are written there
by a static disc overlay and the plugin repoints the RAM table entry when a player picked the BAG1
version.

usage: make_alt_entries.py <disc.bin> <out_package_dir> <c_header> <mod_dir>...
Each mod_dir holds a manifest.toml whose [[overlay]] items (target disc_user) replace stock sectors.
Writes <out_package_dir>/payload/bag1_alt.bin, prints the [[overlay]] block and writes the C index.
Entry roles (who decides the version) come from the main exe tables, see ROLE below."""
import hashlib, os, re, struct, sys

ARCHIVE_LBA, DUMMY_LBA, DUMMY_SECTORS = 179, 224035, 13500
# BAG2 char id 0 = Heat. Tables in the main exe (0x80055180 packs, 0x80055258 models,
# 0x8005510C fever, 0x80055360 stages): [costume A p1 | A p2 | B p1 | B p2].
ROLE = {}            # entry -> (char id, kind) kind: 0 = player 1, 1 = player 2, 2 = fever, 3 = stage
def heat_roles():
    for e in (59, 95, 131, 167): ROLE[e] = (0, 0)
    for e in (60, 96, 132, 168): ROLE[e] = (0, 1)
    for e in (22, 40): ROLE[e] = (0, 2)
    ROLE[200] = (0, 3)
def strike_roles():
    # BAG2 char id 1 = Strike. Tables: packs 73/74/145/146, models 109/110/181/182
    for e in (73, 145): ROLE[e] = (1, 0)   # costume A/B p1
    for e in (74, 146): ROLE[e] = (1, 1)   # costume A/B p2
    for e in (109, 181): ROLE[e] = (1, 0)  # model A/B p1
    for e in (110, 182): ROLE[e] = (1, 1)  # model A/B p2
heat_roles()
strike_roles()

disc, out_pkg, header, mods = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
f = open(disc, 'rb')
def user(lba, n):
    o = bytearray()
    for i in range(n):
        f.seek((lba + i) * 2352 + 24); o += f.read(2048)
    return o

hdr = user(ARCHIVE_LBA, 2)
count = struct.unpack_from('<I', hdr, 4)[0]
table = [struct.unpack_from('<II', hdr, 8 + 8 * i) for i in range(count)]

# collect overlay sectors: lba -> 2048 bytes
patched = {}
for m in mods:
    txt = open(os.path.join(m, 'manifest.toml')).read()
    for blk in txt.split('[[overlay]]')[1:]:
        if 'disc_user' not in blk: continue
        off = int(re.search(r'^offset\s*=\s*(\d+)', blk, re.M).group(1))
        fn = re.search(r'^file\s*=\s*"([^"]+)"', blk, re.M).group(1)
        data = open(os.path.join(m, fn), 'rb').read()
        assert off % 2048 == 0 and len(data) % 2048 == 0, (m, fn)
        for k in range(len(data) // 2048):
            patched[off // 2048 + k] = data[k * 2048:(k + 1) * 2048]

touched = sorted({i for lba in patched for i, (o, s) in enumerate(table)
                  if o // 2048 <= lba - ARCHIVE_LBA < o // 2048 + (s + 2047) // 2048})
alt = bytearray(); index = []; seen = {}
for e in touched:
    o, s = table[e]
    n = (s + 2047) // 2048
    lba0 = ARCHIVE_LBA + o // 2048
    d = user(lba0, n)
    for k in range(n):
        if lba0 + k in patched: d[k * 2048:(k + 1) * 2048] = patched[lba0 + k]
    if e not in ROLE:
        print(f'entry {e}: SKIP (no role)', file=sys.stderr)
        continue
    h = hashlib.sha256(d).hexdigest()
    if h in seen: sec = seen[h]
    else:
        sec = len(alt) // 2048; seen[h] = sec; alt += d
    alt_off = (DUMMY_LBA + sec - ARCHIVE_LBA) * 2048
    index.append((e, ROLE[e], o, s, alt_off, s))
    print(f'entry {e}: role {ROLE[e]}, {n} sectors -> DUMMY+{sec}', file=sys.stderr)
assert len(alt) // 2048 <= DUMMY_SECTORS, 'DUMMY.BIN is full'

os.makedirs(os.path.join(out_pkg, 'payload'), exist_ok=True)
open(os.path.join(out_pkg, 'payload', 'bag1_alt.bin'), 'wb').write(alt)
zero = hashlib.sha256(bytes(len(alt))).hexdigest()
assert user(DUMMY_LBA, len(alt) // 2048) == bytes(len(alt)), 'DUMMY range not empty'
print(f'''[[overlay]]
feature = "bag1-heat"
target = "disc_user"
offset = {DUMMY_LBA * 2048}
file = "payload/bag1_alt.bin"
sha256 = "{hashlib.sha256(alt).hexdigest()}"
expected_sha256 = "{zero}"''')

with open(header, 'w') as h:
    h.write(f"#define B1_ALT_CONTENT_TAG 0x{hashlib.sha256(alt).hexdigest()[:8].upper()}u\n")
    h.write('/* Generated by tools/bag1import/make_alt_entries.py: BUST2.BIN entries with a BAG1 version\n'
            ' * stored in DUMMY.BIN. kind: 0 player 1, 1 player 2, 2 fever (winner), 3 stage. */\n'
            'typedef struct { uint16_t entry; uint8_t chr, kind; uint32_t off, size, alt_off, alt_size; } B1AltEntry;\n'
            'static const B1AltEntry b1_alt_entries[] = {\n')
    for e, (c, k), o, s, ao, asz in index:
        h.write(f'    {{{e}, {c}, {k}, 0x{o:X}u, {s}u, 0x{ao:X}u, {asz}u}},\n')
    h.write('};\n')
print(f'{len(touched)} entries, {len(alt)//2048} sectors used of {DUMMY_SECTORS}', file=sys.stderr)
