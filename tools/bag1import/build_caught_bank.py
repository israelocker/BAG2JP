"""Build the CAUGHT byte bank from pinned originals with BAG2 hold metadata.

Run from the canonical project: py -3.13 tools/bag1import/build_caught_bank.py
Use --check to validate without writing. Neither mode changes the disc payload.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.bag1import.animlib import anim_list, frames, info
from tools.bag1import.rebuild_dfs_members import read_members

CONTRACT = ROOT / 'tools/bag1import/contracts/caught-bank.json'
OUTPUT = ROOT / 'mods-src/bag2jp.feature.bag1-content/bag2jp_caught_bank_data.inc'
CLAMP_LAST_FRAME_OFFSET = 5  # FUN_8002d06c: nonzero clamps rather than wraps frame


def pinned_bytes(path: Path, digest: str) -> bytes:
    """Reject changed source bytes before parsing or producing any output."""
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f'SHA256 mismatch: {path}')
    return data


def extract_clips() -> list[tuple[int, bytes]]:
    """Extract the audited native role, keeping skeleton-specific clips distinct."""
    rows = json.loads(CONTRACT.read_text(encoding='utf-8'))['clips']
    if [row['character'] for row in rows] != [0, 1, 9]:
        raise ValueError('Expected audited BAG1 rivals 0, 1, 9 in bank order')
    clips = []
    for row in rows:
        source = pinned_bytes(ROOT / row['source'], row['source_sha256'])
        members, _padding = read_members(source)
        clip = anim_list(members[1])[70]
        if len(clip) != row['clip_bytes'] or len(clip) % 4:
            raise ValueError('Clip size/alignment changed')
        if hashlib.sha256(clip).hexdigest() != row['clip_sha256']:
            raise ValueError('CAUGHT motion hash changed')
        header, events, metadata, end = info(clip)
        if frames(clip) != 2 or events or clip[end:] != b'\x00\x00':
            raise ValueError('CAUGHT frames/events/tail changed')
        if header != bytes.fromhex('000004000000000000000000'):
            raise ValueError('CAUGHT metadata changed')
        if metadata % 4 or struct.unpack_from('<I', clip)[0] >= len(clip):
            raise ValueError('CAUGHT offsets changed')
        clips.append((row['character'], clip))
    return clips


def generated_text(clips: list[tuple[int, bytes]]) -> str:
    """Keep motion bytes exact; clamp the static pose instead of reanchoring on loops."""
    runtime = []
    for _character, source in clips:
        _header, _events, metadata, _end = info(source)
        clip = bytearray(source)
        clip[metadata + CLAMP_LAST_FRAME_OFFSET] = 1
        runtime.append(bytes(clip))
    data = b''.join(runtime)
    lines = ['/* Generated by tools/bag1import/build_caught_bank.py; do not edit. */',
             f'enum {{ B1CC_BANK_BYTES = {len(data)} }};',
             'static const uint8_t b1cc_data[B1CC_BANK_BYTES] = {']
    for offset in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{byte:02x}' for byte in data[offset:offset + 16]) + ',')
    lines += ['};', 'static const B1CaughtBankEntry b1cc_entries[] = {']
    offset = 0
    for character, clip in clips:
        lines.append(f'    {{{character}u, {offset}u, {len(clip)}u}},')
        offset += len(clip)
    return '\n'.join(lines + ['};', ''])


def main() -> None:
    """Generate, or fail if the checked-in bank no longer matches its sources."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated_text(extract_clips())
    if args.check:
        if OUTPUT.read_bytes() != text.encode('ascii'):
            raise ValueError('Generated bank is stale')
    else:
        OUTPUT.write_bytes(text.encode('ascii'))
    print(json.dumps({'check_only': args.check, 'bytes': 1048,
                      'output_sha256': hashlib.sha256(text.encode('ascii')).hexdigest()}))


if __name__ == '__main__':
    main()
